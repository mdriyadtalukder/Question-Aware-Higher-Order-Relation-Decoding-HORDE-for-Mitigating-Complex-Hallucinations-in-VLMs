import torch

def contrastive_decode(
    original_inputs,
    positive_inputs,
    negative_inputs,
    alpha=0.5,
    beta=0.5,
    max_new_tokens=32
):
    """
    Greedy next-token contrastive decoding.

    Memory-conscious prototype:
    - Three separate image-conditioned branches.
    - No gradient computation.
    - Recomputes each branch per generated token.
    """

    generated_tokens = []
    eos_token_id = vlm_processor.tokenizer.eos_token_id

    # Keep each branch's input tokens and image tensors.
    branch_inputs = [
        {k: v for k, v in inputs.items()}
        for inputs in (
            original_inputs,
            positive_inputs,
            negative_inputs
        )
    ]

    for step in range(max_new_tokens):

        branch_logits = []

        for inputs in branch_inputs:
            with torch.inference_mode():
                outputs = vlm_model(
                    **inputs,
                    use_cache=False
                )

            # Logits for the next token
            logits = outputs.logits[:, -1, :].float()

            branch_logits.append(logits)

            del outputs

        logits_orig, logits_pos, logits_neg = branch_logits

        # HORDE contrastive scoring
        final_logits = (
            logits_orig
            + alpha * (logits_pos - beta * logits_neg)
        )

        # Greedy next-token selection
        next_token = torch.argmax(
            final_logits, dim=-1, keepdim=True
        )

        token_id = int(next_token.item())
        generated_tokens.append(token_id)

        if eos_token_id is not None and token_id == eos_token_id:
            break

        # Append the SAME generated token to all three prefixes.
        # Each branch retains its own image and original prompt.
        for inputs in branch_inputs:
            inputs["input_ids"] = torch.cat(
                [inputs["input_ids"], next_token],
                dim=1
            )

            if "attention_mask" in inputs:
                extra_mask = torch.ones(
                    (inputs["attention_mask"].shape[0], 1),
                    dtype=inputs["attention_mask"].dtype,
                    device=inputs["attention_mask"].device
                )

                inputs["attention_mask"] = torch.cat(
                    [inputs["attention_mask"], extra_mask],
                    dim=1
                )

        del branch_logits, logits_orig, logits_pos
        del logits_neg, final_logits, next_token

    return vlm_processor.decode(
        generated_tokens,
        skip_special_tokens=True
    )


