def mask_object(image, box):
    """Cover a bounding box with a neutral gray mask."""
    result = image.copy()
    x1, y1, x2, y2 = [int(v) for v in box]

    overlay = Image.new("RGB", result.size, (128, 128, 128))
    result.paste(overlay.crop((x1, y1, x2, y2)), (x1, y1))

    return result


def remove_object_inpaint(image, box):
    """
    Approximate object removal using OpenCV inpainting.
    Results may contain artifacts and require visual inspection.
    """
    image_array = np.array(image.convert("RGB"))

    x1, y1, x2, y2 = [int(v) for v in box]

    x1 = max(0, x1)
    y1 = max(0, y1)
    x2 = min(image.width, x2)
    y2 = min(image.height, y2)

    mask = np.zeros(
        (image.height, image.width),
        dtype=np.uint8
    )

    mask[y1:y2, x1:x2] = 255

    result = cv2.inpaint(
        cv2.cvtColor(image_array, cv2.COLOR_RGB2BGR),
        mask,
        5,
        cv2.INPAINT_TELEA
    )

    result = cv2.cvtColor(result, cv2.COLOR_BGR2RGB)

    return Image.fromarray(result)


