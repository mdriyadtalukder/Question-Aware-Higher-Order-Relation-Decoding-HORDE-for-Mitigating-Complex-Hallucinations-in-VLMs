#2.18 Calculate optimization features
import re
from difflib import SequenceMatcher

def get_words(text):
    return set(re.findall(r"[a-z0-9]+", str(text).lower()))


def question_relevance_score(rel, question):
    question_words = get_words(question)

    relation_words = (
        get_words(rel["subject"])
        | get_words(rel["relation"])
        | get_words(rel["object"])
    )

    if not relation_words:
        return 0.0

    overlap = len(question_words & relation_words)
    return overlap / len(relation_words)


def label_similarity(a, b):
    a = normalize_text(a)
    b = normalize_text(b)

    if not a or not b:
        return 0.0

    if a == b:
        return 1.0

    if a in b or b in a:
        return 0.9

    token_a = get_words(a)
    token_b = get_words(b)

    token_score = (
        len(token_a & token_b) / len(token_a | token_b)
        if token_a | token_b else 0.0
    )

    string_score = SequenceMatcher(None, a, b).ratio()

    return max(token_score, string_score)


def grounding_score(rel, detected_objects):
    """
    Estimate whether the subject and object names match
    labels detected in the image.

    This is a label-matching heuristic, not visual verification.
    """
    labels = [obj["name"] for obj in detected_objects]

    if not labels:
        return 0.0

    subject_match = max(
        (label_similarity(rel["subject"], label) for label in labels),
        default=0.0
    )

    object_match = max(
        (label_similarity(rel["object"], label) for label in labels),
        default=0.0
    )

    return (subject_match + object_match) / 2


