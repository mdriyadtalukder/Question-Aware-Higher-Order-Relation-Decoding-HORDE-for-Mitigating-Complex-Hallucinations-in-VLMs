def normalize_yes_no(answer):
    text = str(answer).strip().lower().strip(" .,!\"'")

    # Accept only unambiguous yes/no answers
    if text in {"yes", "yes.", "yes!"}:
        return "yes"
    if text in {"no", "no.", "no!"}:
        return "no"

    # Handle answers such as "The answer is yes."
    import re
    matches = re.findall(r"\b(yes|no)\b", text)

    if len(matches) == 1:
        return matches[0]

    return "unparsed"


